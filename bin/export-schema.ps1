# Generate the CURRENT schema of every managed database as Liquibase changesets:
#   liquibase\<db>\tables\<table>.sql     CREATE TABLE IF NOT EXISTS ...
#   liquibase\<db>\mvs\<mv>.sql           CREATE MATERIALIZED VIEW IF NOT EXISTS ...
#   liquibase\<db>\views\<view>.sql       CREATE OR REPLACE VIEW ...
# Each file is `runOnChange`: on an existing database it changes nothing, on a fresh
# environment it creates the object in its current shape. Never edit them by hand:
# change things with a file in liquibase\<db>\scripts\, apply it, then run this again.
#
# Also creates a new database's folder automatically (changelog.yaml, database.sql,
# tables\ mvs\ scripts\ views\) and adds it to changelog-master.yaml.
#
# Read-only against ClickHouse. Changed files are overwritten; files for objects that no
# longer exist are removed. Databases: -Databases, else LB_DATABASES in .env.
#
#   .\bin\export-schema.ps1
#   .\bin\export-schema.ps1 -Databases raw
param(
    [string[]]$Databases = @(),
    [string]$Url = 'http://localhost:8123',
    [string]$Author = 'christopher'
)
$ErrorActionPreference = 'Stop'
$Root   = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$Lb     = Join-Path $Root 'liquibase'
$Master = Join-Path $Lb 'changelog-master.yaml'
$Utf8   = New-Object Text.UTF8Encoding $false

# --- .env -------------------------------------------------------------------------
$vars = @{}
Get-Content (Join-Path $Root '.env') | Where-Object { $_ -match '^\s*[^#].*=' } | ForEach-Object {
    $k, $v = $_ -split '=', 2; $vars[$k.Trim()] = $v.Trim()
}
$Headers = @{ 'X-ClickHouse-User' = $vars['LIQUIBASE_COMMAND_USERNAME']; 'X-ClickHouse-Key' = $vars['LIQUIBASE_COMMAND_PASSWORD'] }
function Invoke-Ch([string]$sql) {
    $resp = Invoke-WebRequest -Uri $Url -Method Post -Body ($sql + "`nFORMAT JSONEachRow") -UseBasicParsing -Headers $Headers
    $text = [Text.Encoding]::UTF8.GetString($resp.RawContentStream.ToArray())
    @($text -split "`n" | Where-Object { $_.Trim() } | ForEach-Object { $_ | ConvertFrom-Json })
}
function Write-IfChanged([string]$path, [string]$content) {
    $content = $content -replace "`r`n", "`n"
    $old = if (Test-Path $path) { [IO.File]::ReadAllText($path) } else { $null }
    if ($old -eq $content) { return $false }
    New-Item -ItemType Directory -Force -Path (Split-Path $path) | Out-Null
    [IO.File]::WriteAllText($path, $content, $Utf8)
    Write-Host "  $(if ($old) { 'updated' } else { 'added  ' }) $($path.Substring($Lb.Length + 1))"
    return $true
}
function Template([string]$rel) { [IO.File]::ReadAllText((Join-Path $Root "templates\$rel")) }

# --- new database folder ---------------------------------------------------------------
function Ensure-Database([string]$db, [string]$engine) {
    $dbDir = Join-Path $Lb $db
    if (-not (Test-Path (Join-Path $dbDir 'changelog.yaml'))) {
        Write-IfChanged (Join-Path $dbDir 'changelog.yaml') ((Template 'database\changelog.yaml').Replace('__DB__', $db)) | Out-Null
    }
    if (-not (Test-Path (Join-Path $dbDir 'database.sql'))) {
        $sql = (Template 'database\database.sql').Replace('__DB__', $db).Replace('__AUTHOR__', $Author).Replace('ENGINE = Atomic', "ENGINE = $engine")
        Write-IfChanged (Join-Path $dbDir 'database.sql') $sql | Out-Null
    }
    foreach ($sub in 'tables', 'mvs', 'scripts', 'views') { New-Item -ItemType Directory -Force -Path (Join-Path $dbDir $sub) | Out-Null }
    if (-not (Select-String -Path $Master -Pattern ("^\s*file: " + [regex]::Escape($db) + "/changelog\.yaml\s*$") -Quiet)) {
        [IO.File]::AppendAllText($Master, "  - include:`n      file: $db/changelog.yaml`n      relativeToChangelogFile: true`n", $Utf8)
        Write-Host "  NEW DATABASE: added $db to the END of changelog-master.yaml (move it up if something above depends on it)"
        Write-Host "  TODO: grant the liquibase user on $db.* (ops\clickhouse\001-bootstrap-database-and-users.sql)"
    }
}

# --- state changesets ----------------------------------------------------------------
function Convert-Ddl([string]$ddl, [string]$kind) {
    $d = ($ddl -replace " UUID '[0-9a-f-]{36}'", '').TrimEnd()
    switch ($kind) {
        'views'  { $d = $d -replace '^CREATE VIEW ', 'CREATE OR REPLACE VIEW ' }
        'mvs'    { $d = $d -replace '^CREATE MATERIALIZED VIEW ', 'CREATE MATERIALIZED VIEW IF NOT EXISTS ' }
        default  { $d = $d -replace '^CREATE TABLE ', 'CREATE TABLE IF NOT EXISTS ' }
    }
    $d + ';'
}
function State-Changeset([string]$db, [string]$kind, [string]$name, [string]$ddl) {
    $obj = @{ tables = 'table'; mvs = 'materialized view'; views = 'view' }[$kind]
    $rb  = @{ tables = 'empty'; mvs = 'empty'; views = 'empty' }[$kind]
@"
--liquibase formatted sql

--changeset ${Author}:$db-$kind-$name runOnChange:true labels:state
--comment: CURRENT definition of $obj $db.$name. GENERATED by bin/export-schema.ps1: do not edit. Change it with a script in liquibase/$db/scripts/, apply, then regenerate.
$(Convert-Ddl $ddl $kind)
--rollback $rb

"@
}

# --- main ----------------------------------------------------------------------------
if ($Databases.Count -eq 0 -and $vars['LB_DATABASES']) {
    $Databases = $vars['LB_DATABASES'] -split ',' | ForEach-Object { $_.Trim() } | Where-Object { $_ }
}
if ($Databases.Count -eq 0) { throw 'no databases: set LB_DATABASES in .env or pass -Databases' }

$skipped = @()
foreach ($db in $Databases) {
    Write-Host "== $db"
    $dbRow = Invoke-Ch "SELECT engine_full FROM system.databases WHERE name = '$db'"
    if (-not $dbRow) { Write-Warning "$db does not exist in ClickHouse, skipped"; continue }
    Ensure-Database $db $dbRow[0].engine_full

    $rows = Invoke-Ch @"
SELECT name, engine, formatQuery(create_table_query) AS ddl
FROM system.tables
WHERE database = '$db'
  AND NOT is_temporary
  AND name NOT LIKE 'DATABASECHANGELOG%'
  AND name NOT LIKE '.inner%'
ORDER BY name
"@
    $keep = @{}
    foreach ($r in $rows) {
        $kind = switch ($r.engine) { 'View' { 'views' } 'MaterializedView' { 'mvs' } 'Dictionary' { $null } default { 'tables' } }
        if (-not $kind) { $skipped += "$db.$($r.name) (dictionary)"; continue }
        $path = Join-Path $Lb "$db\$kind\$($r.name).sql"
        Write-IfChanged $path (State-Changeset $db $kind $r.name $r.ddl) | Out-Null
        $keep[$path] = $true
    }
    foreach ($kind in 'tables', 'mvs', 'views') {
        Get-ChildItem (Join-Path $Lb "$db\$kind") -Filter *.sql -ErrorAction SilentlyContinue |
            Where-Object { -not $keep.ContainsKey($_.FullName) } | ForEach-Object {
                Remove-Item $_.FullName
                Write-Host "  removed $db\$kind\$($_.Name) (no longer in ClickHouse)"
            }
    }
    Write-Host "  $($rows.Count) objects"
}
if ($skipped) { Write-Warning ("not exported (write a script by hand): " + ($skipped -join ', ')) }
Write-Host "Done. Review with: git diff -- liquibase"
