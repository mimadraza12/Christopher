#!/usr/bin/env bash
# Create a new SCRIPT (a change to run once) in liquibase/<db>/scripts/<year>/.
#
#   bin/new-changeset.sh <db> database                            # just create the database folder
#   bin/new-changeset.sh <db> table   <table>                    # CREATE TABLE
#   bin/new-changeset.sh <db> column  <table> <column>           # ADD COLUMN
#   bin/new-changeset.sh <db> mv      <mv>    [<source_table>]   # CREATE MATERIALIZED VIEW (+ target table)
#   bin/new-changeset.sh <db> view    <view>  [<source_table>]   # CREATE OR REPLACE VIEW
#   bin/new-changeset.sh <db> script  <slug>  [<table>]          # anything else: type change, drop, data fix
#
# e.g. bin/new-changeset.sh analytics column vendors region
#
# Everything is a script. tables/ mvs/ views/ hold the CURRENT schema and are generated by
# bin/export-schema.ps1 after the script is applied: never edit them by hand.
# Scripts must be safe on objects that are already current (a fresh environment builds
# tables/ first, then runs every script): use IF [NOT] EXISTS and preconditions.
#
# A database that has no folder yet gets one automatically (changelog.yaml, database.sql,
# tables/ mvs/ scripts/ views/) and is appended to changelog-master.yaml.
#
# AUTHOR defaults to `git config user.email` local part.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
T="$ROOT/templates/changesets"
TD="$ROOT/templates/database"
MASTER="$ROOT/liquibase/changelog-master.yaml"
DB="${1:?database (folder under liquibase/, e.g. raw or analytics)}"
kind="${2:?kind: database|table|column|view|mv|script}"
if [ "$kind" = "database" ]; then name=""; else name="${3:?name}"; fi
extra="${4:-}"
[[ "$DB" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || { echo "invalid database name: $DB" >&2; exit 1; }
LB="$ROOT/liquibase/$DB"
AUTHOR="${AUTHOR:-$(git -C "$ROOT" config user.email 2>/dev/null | cut -d@ -f1)}"
AUTHOR="${AUTHOR:-unknown}"
TODAY="$(date +%F)"

next_seq() { # next NNN for today within a directory
  local dir="$1" n
  n=$(ls "$dir" 2>/dev/null | grep -c "^$TODAY-" || true)
  printf '%03d' $((n + 1))
}

render() { # template out_file id
  sed -e "s/__AUTHOR__/$AUTHOR/g" -e "s/__ID__/$3/g" -e "s/__DB__/$DB/g" \
      -e "s/__TABLE__/${TABLE:-__TABLE__}/g" -e "s/__COLUMN__/${COLUMN:-__COLUMN__}/g" \
      -e "s/__VIEW__/${VIEW:-__VIEW__}/g" -e "s/__MV__/${MV:-__MV__}/g" \
      "$1" > "$2"
  [ -e "$2" ] && echo "created ${2#"$ROOT/"}"
}

ensure_database() { # create liquibase/<db>/ + register it in the master changelog
  local created=0
  if [ ! -f "$LB/changelog.yaml" ]; then
    mkdir -p "$LB"
    sed -e "s/__DB__/$DB/g" "$TD/changelog.yaml" > "$LB/changelog.yaml"
    sed -e "s/__DB__/$DB/g" -e "s/__AUTHOR__/$AUTHOR/g" "$TD/database.sql" > "$LB/database.sql"
    created=1
  fi
  for sub in tables mvs scripts views; do
    mkdir -p "$LB/$sub"
    [ -n "$(ls -A "$LB/$sub")" ] || touch "$LB/$sub/.gitkeep"
  done
  if ! grep -qE "^[[:space:]]*file: $DB/changelog\.yaml[[:space:]]*$" "$MASTER"; then
    printf '  - include:\n      file: %s/changelog.yaml\n      relativeToChangelogFile: true\n' "$DB" >> "$MASTER"
    created=1
  fi
  if [ "$created" = 1 ]; then
    echo "NEW DATABASE '$DB':"
    echo "  created liquibase/$DB/ (changelog.yaml, database.sql, tables/ mvs/ scripts/ views/)"
    echo "  added   $DB/changelog.yaml at the END of liquibase/changelog-master.yaml"
    echo "          -> move it up if '$DB' must exist before a database listed above it"
    echo "  TODO    grant the liquibase user on $DB.* (ops/clickhouse/001-bootstrap-database-and-users.sql)"
  fi
}

refuse_existing() { [ -e "$1" ] && { echo "exists: $1" >&2; exit 1; } || true; }

ensure_database

SCRIPTS="$LB/scripts/$(date +%Y)"; mkdir -p "$SCRIPTS"
new_script() { # template slug
  local seq f; seq=$(next_seq "$SCRIPTS"); f="$SCRIPTS/$TODAY-$seq-$DB-$2.sql"; refuse_existing "$f"
  render "$1" "$f" "$TODAY-$seq-$DB-$2"
}

case "$kind" in
  database) ;;  # folder only
  table)  TABLE="$name";                                 new_script "$T/create-table.sql"      "$name-create" ;;
  column) TABLE="$name"; COLUMN="${extra:?column name}"; new_script "$T/add-column.sql"        "$name-add-$COLUMN" ;;
  mv)     MV="$name"; TABLE="${extra:-__TABLE__}";       new_script "$T/materialized-view.sql" "$name-create" ;;
  view)   VIEW="$name"; TABLE="${extra:-__TABLE__}";     new_script "$T/view.sql"              "$name" ;;
  script) TABLE="${extra:-__TABLE__}";                   new_script "$T/data-script.sql"       "$name" ;;
  *) echo "unknown kind: $kind" >&2; exit 1 ;;
esac
echo "after applying: .\\bin\\export-schema.ps1 (regenerates tables/ mvs/ views/), then commit both"
